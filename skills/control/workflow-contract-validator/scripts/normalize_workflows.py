def audit_action_dependencies(actions):
    """Reject unknown references and ancestor cycles before projection."""

    def check_graph(action_id, ancestors):
        if action_id not in actions:
            raise ValueError(f"unknown action dependency: {action_id}")
        if action_id in ancestors:
            raise ValueError(f"action dependency cycle: {action_id}")
        for child in actions[action_id].depends_on:
            check_graph(child, ancestors | {action_id})

    for action_id in actions:
        check_graph(action_id, set())


