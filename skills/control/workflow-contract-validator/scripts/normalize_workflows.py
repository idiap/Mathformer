def canonical_id(category, native):
    """Materialize an explicit, category-qualified alias mapping; collisions fail."""
    return (
        category
        + "_"
        + re.sub(r"[^a-z0-9_]+", "_", native.lower()).strip("_")
        + "_workflow"
    )


def source(path, selector):
    return {
        "path": path,
        "selector": selector,
        "digest": "sha256:"
        + hashlib.sha256((REPO_ROOT / path).read_bytes()).hexdigest(),
    }


