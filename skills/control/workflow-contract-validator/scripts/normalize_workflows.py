def native_interface(descriptor, actions, binding, extra_args=False):
    """Expose the real hub boundary, including dry-run/preflight/failure payloads."""
    descriptor["types"] = {
        "RunContext": {
            "schema": "../../hub-interface.schema.json#/$defs/RunContext",
            "representation": "value",
        },
        "ExtraArguments": {
            "schema": {"type": "array", "items": {"type": "string"}},
            "representation": "value",
        },
        "HubResult": {
            "schema": "../../hub-interface.schema.json#/$defs/HubResult",
            "representation": "value",
        },
    }
    ports = {"context": {"type": "RunContext"}}
    arguments = {"context": {"ref": "inputs.context"}}
    if extra_args:
        ports["extra_args"] = {"type": "ExtraArguments"}
        arguments["extra_args"] = {"ref": "inputs.extra_args"}
    descriptor["inputs"] = ports
    descriptor["outputs"] = {
        "result": {"type": "HubResult", "value": {"ref": "steps.invoke.outputs.result"}}
    }
    descriptor["operations"] = {
        "invoke": {
            "inputs": ports,
            "outputs": {"result": {"type": "HubResult"}},
            "execution": {"mode": "mixed", "binding": binding},
        }
    }
    descriptor["flow"] = {
        "kind": "sequence",
        "steps": [
            {
                "id": "invoke",
                "kind": "call",
                "operation": "invoke",
                "arguments": arguments,
            },
        ],
    }
    writes = set()
    visited = set()

    def visit(action_id):
        if action_id in visited:
            return
        visited.add(action_id)
        item = actions[action_id]
        writes.update(item.writes)
        for dependency in item.depends_on:
            visit(dependency)

    targets = descriptor["extensions"]["mathformer.source"]["contract"].get(
        "action_ids", [binding["target"]]
    )
    for target in targets:
        visit(target)
    # Wrapper report writes are conditional on RunContext.write_report.
    writes.add("artifacts/workflow_hub/")
    descriptor["policy"]["effects"] = {
        "filesystem": {
            "read": ["repository", "native_runtime_inputs"],
            "write": sorted(writes),
        },
        "network": ["native_binding_capabilities_require_qualification"],
        "external_write": ["native_binding_capabilities_require_qualification"],
    }
    descriptor["policy"]["authority"]["allowed"] = ["invoke_registered_native_workflow"]
    descriptor["extensions"]["mathformer.native_boundary"] = {
        "execution": "Existing scripts/mathformer.py controller only; MCP can dispatch the canonical identity, but no general v1 DAG interpreter is supplied.",
        "context_fields": [
            "dry_run",
            "json_output",
            "keep_going",
            "allow_mutating",
            "write_report",
        ],
        "effects_status": "partial_native_declarations",
        "qualification_capability_names_are_not_runtime_grants": True,
        "failure_policy": "Return the native ok/status payload unchanged; do not turn a failed subprocess or preflight into acceptance.",
        "scientific_payloads": "HubResult describes the transport envelope, not backend reports or proof artifacts.",
    }


