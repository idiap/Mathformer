def add_standard_docstrings(body: str) -> str:
    """Insert short function comments into generated controlled-case bodies."""
    for function_name, docstring in FUNCTION_DOCSTRINGS.items():
        pattern = rf"(def {function_name}\([^)]*\)(?: -> [^:]+)?:\n)(?!\s+['\"])"
        body = re.sub(pattern, rf'\1    """{docstring}"""\n', body)
    return body


def collect_statement(parse_packet: dict[str, Any]) -> dict[str, Any]:
    """Document the responsibility of ``collect_statement``.

    Motivation:
        Make agent behavior explicit, scoped, and reproducible for specialized Mathformer tasks.

    Intent:
        Provide the local operation named ``collect_statement`` while preserving the surrounding module contract.

    Inputs:
        Accepts the parameters declared in the signature; callers should satisfy the invariants documented by neighboring code and tests.

    Outputs:
        Returns the value or side effect required by the workflow, with errors kept explicit at the call boundary.
    """
    for unit in parse_packet.get("units", []):
        if unit.get("kind") == "theorem_statement":
            return unit
    return parse_packet.get("units", [{}])[0]


def render_module(
    case_id: str,
    parse_packet: dict[str, Any],
    assumptions: dict[str, Any],
    grounding: dict[str, Any],
) -> str:
    """Document the responsibility of ``render_module``.

    Motivation:
        Make agent behavior explicit, scoped, and reproducible for specialized Mathformer tasks.

    Intent:
        Render structured information into a human-readable or machine-consumable representation.

    Inputs:
        Accepts the parameters declared in the signature; callers should satisfy the invariants documented by neighboring code and tests.

    Outputs:
        Returns the value or side effect required by the workflow, with errors kept explicit at the call boundary.
    """
    if case_id not in CASE_BODIES:
        raise ValueError(f"Unsupported SymPy controlled case: {case_id}")
    statement = collect_statement(parse_packet)
    anchors = sorted(
        {
            anchor
            for unit in parse_packet.get("units", [])
            for anchor in unit.get("source_anchors", [])
        }
    )
    claim = {
        "id": case_id,
        "backend": "sympy",
        "style": "sympy_equational_trace",
        "source_anchors": anchors,
        "statement_nl": statement.get("literal_nl", ""),
        "statement_latex": statement.get("literal_latex", ""),
        "formal_latex": CASE_BODIES[case_id]["formal_latex"],
        "assumptions": assumptions.get("assumptions", []),
        "grounded_apis": [
            {"concept": item.get("concept"), "chosen_api": item.get("chosen_api")}
            for item in grounding.get("concepts", [])
        ],
    }
    body = add_standard_docstrings(
        textwrap.dedent(CASE_BODIES[case_id]["body"]).strip()
    )
    return MODULE_TEMPLATE.substitute(
        statement_nl=claim["statement_nl"],
        statement_latex=claim["statement_latex"],
        formal_latex=claim["formal_latex"],
        source_anchors=", ".join(anchors),
        imports=CASE_BODIES[case_id]["imports"],
        claim_json=pformat(claim, sort_dicts=True, width=100),
        body=body,
    )


def main() -> int:
    """Document the responsibility of ``main``.

    Motivation:
        Make agent behavior explicit, scoped, and reproducible for specialized Mathformer tasks.

    Intent:
        Serve as the command-line entry point and coordinate argument parsing, execution, and reporting.

    Inputs:
        Accepts the parameters declared in the signature; callers should satisfy the invariants documented by neighboring code and tests.

    Outputs:
        Returns the value or side effect required by the workflow, with errors kept explicit at the call boundary.
    """
    parser = argparse.ArgumentParser()
    parser.add_argument("--parse-packet", type=Path)
    parser.add_argument("--assumptions", type=Path)
    parser.add_argument("--grounding", type=Path)
    parser.add_argument("--output", type=Path)
    parser.add_argument("--report", type=Path)
    parser.add_argument("--self-test", action="store_true")
    parser.add_argument("--json", action="store_true")
    args = parser.parse_args()

    if args.self_test:
        root = Path("artifacts/sympy/wiki_sum_first_odd_numbers")
        if not (root / "api_grounding.json").exists():
            subprocess.run([sys.executable, "tests/sympy/run_wiki_case.py"], check=True)
        args.parse_packet = Path(
            "artifacts/sympy/wiki_sum_first_odd_numbers/parse_packet.json"
        )
        args.assumptions = Path(
            "artifacts/sympy/wiki_sum_first_odd_numbers/assumptions.json"
        )
        args.grounding = Path(
            "artifacts/sympy/wiki_sum_first_odd_numbers/api_grounding.json"
        )
        args.output = Path("artifacts/sympy/self_test/AutoformalizedSelfTest.py")
    missing = [
        name
        for name in ["parse_packet", "assumptions", "grounding"]
        if getattr(args, name) is None
    ]
    if missing:
        parser.error(
            f"missing required arguments: {', '.join('--' + item.replace('_', '-') for item in missing)}"
        )

    parse_packet = json.loads(args.parse_packet.read_text(encoding="utf-8"))
    assumptions = json.loads(args.assumptions.read_text(encoding="utf-8"))
    grounding = json.loads(args.grounding.read_text(encoding="utf-8"))
    case_id = parse_packet.get("case_id") or collect_statement(parse_packet).get(
        "case_id"
    )
    if not isinstance(case_id, str) or not case_id:
        raise ValueError("Parse packet has no supported case_id")
    if args.output is None:
        args.output = Path("MathformerSympy") / CASE_OUTPUTS.get(
            case_id, f"Autoformalized{case_id.title().replace('_', '')}.py"
        )
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(
        render_module(case_id, parse_packet, assumptions, grounding) + "\n",
        encoding="utf-8",
    )
    report = {
        "backend": "sympy",
        "style": "sympy_equational_trace",
        "case_id": case_id,
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "output": str(args.output),
        "source_anchors": sorted(
            {
                anchor
                for unit in parse_packet.get("units", [])
                for anchor in unit.get("source_anchors", [])
            }
        ),
        "status": "drafted",
        "placeholder_free": True,
    }
    if args.report:
        args.report.parent.mkdir(parents=True, exist_ok=True)
        args.report.write_text(
            json.dumps(report, indent=2, sort_keys=True) + "\n", encoding="utf-8"
        )
    print(
        json.dumps(report, indent=2, sort_keys=True)
        if args.json
        else f"wrote {args.output}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
