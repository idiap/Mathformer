"""Synthetic repository data; all plugin implementations remain unmodified."""

import hashlib
import json
import os
import shutil
import subprocess

import sync_agent_plugins as plugins
from workflow_catalog import WORKFLOWS

DESCRIPTOR = str(WORKFLOWS / "route/route_skills_plugin_check_workflow/workflow.yaml")
SCHEMA = str(WORKFLOWS / "hub-interface.schema.json")


def populate(root, source, document, mode="success"):
    if root.exists():
        shutil.rmtree(root)
    root.mkdir(parents=True)
    for relative in [
        "scripts/sync_agent_plugins.py",
        "scripts/workflow_catalog.py",
        "tests/agent_clients/test_agent_plugins.py",
        "skills/control/workflow-contract-validator/scripts/validate_workflow.py",
        "skills/control/workflow-contract-validator/references/workflow.schema.json",
        SCHEMA,
    ]:
        dest = root / relative
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(source / relative, dest)
    (root / "pyproject.toml").write_text('[project]\nversion = "0.1.0"\n')
    (root / "LICENSE").write_text("MIT\n")
    (root / "LICENSES").mkdir()
    (root / "LICENSES/MIT.txt").write_text("MIT\n")
    skill = root / "skills/fixture/demo/SKILL.md"
    skill.parent.mkdir(parents=True)
    skill.write_text(
        "---\nname: demo\ndescription: Check synthetic plugin data.\n---\nFixture.\n"
    )
    (root / "REUSE.toml").write_text(
        'version = 1\n[[annotations]]\npath = ["*"]\n'
        'SPDX-FileContributor = ["Danilo Gusicuma <danilo.gusicuma@idiap.ch>"]\n'
    )
    descriptor = root / DESCRIPTOR
    descriptor.parent.mkdir(parents=True)
    content = json.dumps(document)
    descriptor.write_text(content)
    (root / WORKFLOWS / "catalog.json").write_text(
        json.dumps(
            {
                "schema_version": "mathformer.normalized-workflow-catalog/v1",
                "counts": {"route": 1},
                "workflows": [
                    {
                        "id": document["id"],
                        "aliases": document["aliases"],
                        "category": "route",
                        "path": "route/route_skills_plugin_check_workflow/workflow.yaml",
                        "owner_skill": "skills/fixture/demo/SKILL.md",
                        "description": document["description"],
                        "descriptor_digest": "sha256:"
                        + hashlib.sha256(content.encode()).hexdigest(),
                    }
                ],
            }
        )
    )
    plugins.synchronize(root, check=False)
    # A tiny, attributed history exercises the real unit test's Git queries.
    # Git receives no user/global configuration, hooks, signing, or credentials.
    env = {**os.environ, "GIT_CONFIG_GLOBAL": os.devnull, "GIT_CONFIG_NOSYSTEM": "1"}
    (root / "README.md").write_text("Synthetic plugin repository.\n")
    for args in [
        ["init", "-q"],
        ["add", "README.md"],
        [
            "-c",
            "user.name=Danilo Gusicuma",
            "-c",
            "user.email=danilo.gusicuma@idiap.ch",
            "-c",
            "commit.gpgSign=false",
            "-c",
            f"core.hooksPath={os.devnull}",
            "commit",
            "-qm",
            "fixture",
        ],
    ]:
        subprocess.run(
            ["git", *args],
            cwd=root,
            env=env,
            check=True,
            capture_output=True,
            text=True,
        )
    if mode == "drift":
        (root / plugins.PLUGIN / "skills/demo/SKILL.md").write_text(
            "stale projection\n"
        )
        stale = root / plugins.PLUGIN / "skills/obsolete/SKILL.md"
        stale.parent.mkdir()
        stale.write_text("Generated by `scripts/sync_agent_plugins.py`\n")
    elif mode == "missing_check":
        (root / "scripts/sync_agent_plugins.py").unlink()
    elif mode == "missing_test":
        (root / "tests/agent_clients/test_agent_plugins.py").unlink()
    elif mode != "success":
        raise ValueError(mode)
