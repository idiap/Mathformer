"""Deterministic repository inputs for real plugin sync/check subprocesses.

No provider is used by this route. Production implementations are copied intact
and run exclusively in this disposable tree; nothing substitutes their steps.
"""

import hashlib
import json
import shutil

import sync_agent_plugins as plugins
from workflow_catalog import WORKFLOWS

DESCRIPTOR = str(WORKFLOWS / "route/route_skills_plugin_sync_workflow/workflow.yaml")
SCHEMA = str(WORKFLOWS / "hub-interface.schema.json")


def populate(root, source, document, mode="fresh"):
    if root.exists():
        shutil.rmtree(root)
    root.mkdir(parents=True)
    for relative in [
        "scripts/sync_agent_plugins.py",
        "scripts/workflow_catalog.py",
        "skills/control/workflow-contract-validator/references/workflow.schema.json",
        SCHEMA,
    ]:
        target = root / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(source / relative, target)
    (root / "pyproject.toml").write_text('[project]\nversion = "0.1.0"\n')
    (root / "LICENSE").write_text("MIT\n")
    (root / "LICENSES").mkdir()
    (root / "LICENSES/MIT.txt").write_text("MIT\n")
    skill = root / "skills/fixture/demo/SKILL.md"
    skill.parent.mkdir(parents=True)
    skill.write_text(
        "---\nname: demo\ndescription: Synthetic plugin projection.\n---\nFixture.\n"
    )
    (root / "REUSE.toml").write_text(
        'version = 1\n[[annotations]]\npath = ["*"]\n'
        'SPDX-FileContributor = ["Danilo Gusicuma <danilo.gusicuma@idiap.ch>"]\n'
    )
    descriptor = root / DESCRIPTOR
    descriptor.parent.mkdir(parents=True)
    content = json.dumps(document)
    descriptor.write_text(content)
    (root / WORKFLOWS / "catalog.json").write_text(
        json.dumps(
            {
                "schema_version": "mathformer.normalized-workflow-catalog/v1",
                "counts": {"route": 1},
                "workflows": [
                    {
                        "id": document["id"],
                        "aliases": document["aliases"],
                        "category": "route",
                        "path": "route/route_skills_plugin_sync_workflow/workflow.yaml",
                        "owner_skill": "skills/fixture/demo/SKILL.md",
                        "description": document["description"],
                        "descriptor_digest": "sha256:"
                        + hashlib.sha256(content.encode()).hexdigest(),
                    }
                ],
            }
        )
    )
    if mode != "fresh":
        plugins.synchronize(root, check=False)
    if mode in ["drift", "partial", "companion"]:
        (root / plugins.PLUGIN / "skills/demo/SKILL.md").write_text(
            "outdated projection\n"
        )
        for name in ["a-old", "b-old"]:
            stale = root / plugins.PLUGIN / "skills" / name
            stale.mkdir()
            (stale / "SKILL.md").write_text(
                "Generated by `scripts/sync_agent_plugins.py`\n"
            )
            (stale / "workflow.yaml").write_text(
                "# Generated by `scripts/sync_agent_plugins.py`\n{}\n"
            )
        if mode == "partial":
            stale = root / plugins.PLUGIN / "skills/z-unmanaged"
            stale.mkdir()
            (stale / "SKILL.md").write_text("User-owned entrypoint\n")
        if mode == "companion":
            (root / plugins.PLUGIN / "skills/b-old/workflow.yaml").write_text(
                "User-owned companion\n"
            )
    elif mode == "missing_command":
        (root / "scripts/sync_agent_plugins.py").unlink()
    elif mode == "missing_skills":
        shutil.rmtree(root / "skills")
    elif mode == "invalid_toml":
        (root / "pyproject.toml").write_text("invalid [ toml")
    elif mode == "missing_license":
        (root / "LICENSE").unlink()
    elif mode == "catalog_drift":
        descriptor.write_text(content + "\n")
    elif mode == "obstructed":
        path = root / plugins.PLUGIN / ".codex-plugin/plugin.json"
        path.unlink()
        path.mkdir()
    elif mode not in ["fresh", "synced", "no_catalog"]:
        raise ValueError(mode)
    if mode == "no_catalog":
        shutil.rmtree(root / WORKFLOWS)
        (root / WORKFLOWS.parent / "workflow.schema.json").unlink()
