DESCRIPTOR = "skills/control/workflow-contract-validator/references/normalized-workflows/hub/hub_skills_plugin_sync_workflow/workflow.yaml"


def oracle():
    scope = {
        "__file__": str(ROOT / "scripts/sync_agent_plugins.py"),
        "__name__": "original_sync",
    }
    exec((ROOT / "tests/mcp/fixtures/plugin_sync_original.py.txt").read_text(), scope)
    return scope["synchronize"]


def snapshot(doc):
    def asset(path, text):
        return dict(
            path=path,
            content=text,
            encoding="text",
            sha256=hashlib.sha256(text.encode()).hexdigest(),
        )

    return [asset(DESCRIPTOR, json.dumps(doc))] + [
        asset(r["path"], (ROOT / r["path"]).read_text())
        for r in doc["provenance"]["sources"]
    ]


def prepare(root, mode):
    fixture(root, mode)
    if mode in ["managed", "unmanaged", "unmarked_companion"]:
        put(
            root,
            native.PLUGIN / "skills/a-old/SKILL.md",
            "Generated by `scripts/sync_agent_plugins.py`",
        )
        put(
            root,
            native.PLUGIN / "skills/a-old/workflow.yaml",
            "# Generated by `scripts/sync_agent_plugins.py`\nold",
        )
        put(
            root,
            native.PLUGIN / "skills/z-old/SKILL.md",
            (
                "unmanaged"
                if mode == "unmanaged"
                else "Generated by `scripts/sync_agent_plugins.py`"
            ),
        )
        put(
            root,
            native.PLUGIN / "skills/z-old/workflow.yaml",
            (
                "keep"
                if mode == "unmarked_companion"
                else "# Generated by `scripts/sync_agent_plugins.py`\nold"
            ),
        )
        if mode == "managed":
            put(root, native.PLUGIN / "skills/z-old/extra", "keep directory")
    return root


class SyncTests(unittest.TestCase):
    def test_native_original_parity(self):
        for mode in [
            "missing",
            "parity",
            "changed",
            "catalog",
            "managed",
            "unmanaged",
            "unmarked_companion",
            "destination_directory",
            "malformed",
            "duplicate",
            "missing_catalog",
            "comparison_failure",
        ]:
            for check in [True, False]:
                with (
                    self.subTest(mode=mode, check=check),
                    tempfile.TemporaryDirectory() as a,
                    tempfile.TemporaryDirectory() as b,
                ):
                    left = prepare(Path(a), mode)
                    right = prepare(Path(b), mode)
                    try:
                        expected = oracle()(left, check=check)
                    except (OSError, ValueError) as error:
                        with self.assertRaises(type(error)):
                            native.synchronize(right, check=check)
                    else:
                        self.assertEqual(
                            native.synchronize(right, check=check), expected
                        )
                    self.assertEqual(tree(left), tree(right))

    def test_registered_mcp_lunar(self):
        asyncio.run(self.scenario())

    async def scenario(self):
        doc = yaml.safe_load(Path(os.environ["WORKFLOW_CONTRACT_PATH"]).read_text())
        self.assertEqual(doc["id"], "hub_skills_plugin_sync_workflow")
        self.assertEqual(doc["lifecycle"], "active")
        self.assertEqual(
            doc,
            json.loads(
                (
                    ROOT
                    / "skills/control/workflow-contract-validator/references/plugin-sync.workflow.json"
                ).read_text()
            ),
        )
        for row in doc["provenance"]["sources"]:
            self.assertEqual(
                row["digest"],
                "sha256:"
                + hashlib.sha256((ROOT / row["path"]).read_bytes()).hexdigest(),
            )
        base = ROOT / "artifacts/workflow_hub"
        base.mkdir(parents=True, exist_ok=True)
        manager = SessionManager()
        self.assertIn(
            "register_plugin_sync_tools(mcp, _graph_layout_write_policy)",
            (ROOT / "scripts/mcp_server.py").read_text(),
        )
        async with manager.open(
            "plugin-sync",
            StdioConfig(
                command=sys.executable,
                args=[str(ROOT / "scripts/plugin_sync_tools.py")],
                cwd=str(ROOT),
            ),
            {},
        ) as remote:
            try:
                tools = [
                    t.model_dump(by_alias=True, exclude_none=True)
                    for t in await remote.tools()
                ]

                def compile(document, inventory=tools):
                    assets = snapshot(document)
                    c = compile_workflow(
                        "mcp:plugin-sync",
                        workflow_documents([DESCRIPTOR], assets)[0],
                        inventory,
                    )
                    return c, assets

                compiled, assets = compile(doc)
                self.assertTrue(compiled["runnable"], compiled["diagnostics"])
                self.assertTrue(compiled["runtime_source"])
                self.assertEqual(set(compiled["bindings"]), set(doc["operations"]))
                self.assertFalse(compile(doc, [])[0]["runnable"])

                async def allow():
                    pass

                async def run(root, check=False, document=doc):
                    c, a = compile(document)
                    self.assertTrue(c["runnable"], c["diagnostics"])
                    return await execute(
                        c, a, {"root": str(root), "check": check}, remote, allow
                    )

                for mode in [
                    "missing",
                    "parity",
                    "changed",
                    "catalog",
                    "managed",
                    "unmanaged",
                    "unmarked_companion",
                    "destination_directory",
                    "malformed",
                    "duplicate",
                    "mismatch",
                    "no_skills",
                    "missing_catalog",
                    "catalog_digest",
                    "catalog_escape",
                    "io_error",
                    "comparison_failure",
                ]:
                    for check in [True, False]:
                        with (
                            self.subTest(mode=mode, check=check),
                            tempfile.TemporaryDirectory(dir=base) as a,
                            tempfile.TemporaryDirectory() as b,
                        ):
                            root = prepare(Path(a), mode)
                            other = prepare(Path(b), mode)
                            before = tree(root)
                            try:
                                expected = oracle()(other, check=check)
                            except (OSError, ValueError):
                                expected = None
                            result = await run(root, check)
                            self.assertEqual(tree(root), tree(other))
                            if expected is None:
                                self.assertEqual(result["status"], "failed", result)
                                self.assertIsNone(result["outputs"])
                                self.assertEqual(
                                    result["calls"][-1]["status"], "rejected"
                                )
                                self.assertNotIn(
                                    "mathformer_plugin_sync_return_differences",
                                    [c["tool"] for c in result["calls"]],
                                )
                                if mode == "unmanaged" and not check:
                                    self.assertTrue(
                                        (root / native.PLUGIN / "LICENSE").exists()
                                    )
                                    self.assertFalse(
                                        (root / native.PLUGIN / "skills/a-old").exists()
                                    )
                                    self.assertTrue(
                                        (
                                            root
                                            / native.PLUGIN
                                            / "skills/z-old/SKILL.md"
                                        ).exists()
                                    )
                                continue
                            self.assertEqual(result["status"], "accepted", result)
                            self.assertEqual(
                                result["outputs"], {"differences": expected}
                            )
                            self.assertTrue(result["runtime"]["effect_records"])
                            self.assertTrue(result["runtime"]["provenance"])
                            self.assertTrue(result["replay_artifacts"])
                            names = [
                                c["tool"].removeprefix("mathformer_plugin_sync_")
                                for c in result["calls"]
                            ]
                            self.assertEqual(
                                names[:3], ["project", "discover_stale", "compare_pack"]
                            )
                            if check:
                                self.assertEqual(
                                    names[3:],
                                    [
                                        "skip_sweep",
                                        "reset_cursor",
                                        "skip_sweep",
                                        "return_differences",
                                    ],
                                )
                                self.assertEqual(tree(root), before)
                            else:
                                n = len(native.expected_files(root))
                                stale_count = (
                                    2
                                    if mode in ["managed", "unmarked_companion"]
                                    else 0
                                )
                                self.assertEqual(
                                    names[3:],
                                    ["write_next"] * n
                                    + ["reset_cursor"]
                                    + ["remove_next"] * max(1, stale_count)
                                    + ["return_differences"],
                                )
                                clean = await run(root, True)
                                self.assertEqual(clean["outputs"], {"differences": []})
                with tempfile.TemporaryDirectory(dir=base) as directory:
                    root = prepare(Path(directory), "missing")
                    count = len(native.expected_files(root))
                    exact = deepcopy(doc)
                    exact["flow"]["steps"][3]["max_iterations"] = count
                    result = await run(root, document=exact)
                    self.assertEqual(result["status"], "accepted", result)
                    bounded = deepcopy(doc)
                    bounded["flow"]["steps"][3]["max_iterations"] = 1
                    result = await run(root, document=bounded)
                    self.assertEqual(result["status"], "failed", result)
                    self.assertEqual(len(result["calls"]), 4)
                    self.assertIsNone(result["outputs"])
                    budget = deepcopy(doc)
                    budget["policy"]["limits"]["max_operation_calls"] = 3
                    result = await run(root, True, budget)
                    self.assertEqual(result["status"], "failed", result)
                    self.assertEqual(
                        sum(
                            bool(c.get("transport_call_performed"))
                            for c in result["calls"]
                        ),
                        3,
                    )
                    self.assertIn("budget", str(result).lower())
                    state = dict(
                        root=str(root),
                        expected={},
                        expected_order=[],
                        stale=[],
                        differences=["original"],
                        cursor=0,
                    )
                    for op in ["write_next", "remove_next"]:
                        self.assertEqual(
                            await remote.call(
                                "mathformer_plugin_sync_" + op, {"state": state}
                            ),
                            {"state": state, "done": True},
                        )
                    # Last item reports completion at the specialization's maximum cursor.
                    state.update(
                        expected={f"plugins/mathformer/x{i}": "" for i in range(10000)},
                        expected_order=[
                            f"plugins/mathformer/x{i}" for i in range(10000)
                        ],
                        cursor=9999,
                    )
                    out = await remote.call(
                        "mathformer_plugin_sync_write_next", {"state": state}
                    )
                    self.assertTrue(out["done"])
                    self.assertEqual(out["state"]["cursor"], 10000)
                    self.assertEqual(out["state"]["differences"], ["original"])
                    # Guard overlarge state before writes, independently of loop limits.
                    state["expected"]["plugins/mathformer/overflow"] = ""
                    state["expected_order"].append("plugins/mathformer/overflow")
                    with self.assertRaises(Exception):
                        await remote.call(
                            "mathformer_plugin_sync_write_next", {"state": state}
                        )
                    state["expected_order"] = []
                    with self.assertRaises(Exception):
                        await remote.call(
                            "mathformer_plugin_sync_write_next", {"state": state}
                        )
                with tempfile.TemporaryDirectory(dir=base) as directory:
                    root = prepare(Path(directory), "managed")
                    bounded = deepcopy(doc)
                    bounded["flow"]["steps"][5]["max_iterations"] = 1
                    result = await run(root, document=bounded)
                    self.assertEqual(result["status"], "failed", result)
                    self.assertFalse((root / native.PLUGIN / "skills/a-old").exists())
                    self.assertTrue(
                        (root / native.PLUGIN / "skills/z-old/SKILL.md").exists()
                    )
                    self.assertNotIn(
                        "mathformer_plugin_sync_return_differences",
                        [c["tool"] for c in result["calls"]],
                    )
            except BaseException:
                import traceback

                traceback.print_exc()
                raise
        self.assertFalse(manager.active)


if __name__ == "__main__":
    unittest.main(verbosity=2)
