"""Reviewed human-scale reasoning projections for named Mathformer workflows.

These specifications describe interpretive epistemic topology.  Their material
hook lists select the canonical skill context used by projected agents; they do
not assert that the detailed hook implementations execute inside those agents.
The detailed material workflows remain separate PRISM entrypoints.
"""

