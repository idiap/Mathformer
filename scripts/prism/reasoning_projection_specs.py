def stage(
    occurrence_id: str,
    method: str,
    output_type: str,
    semantic_kind: str,
    rationale: str,
    hooks: list[str],
    *,
    relation: str | None = None,
    sources: list[str] | None = None,
    input_type: str | None = None,
) -> dict[str, Any]:
    return {
        "id": occurrence_id,
        "method": method,
        "output_type": output_type,
        "semantic_kind": semantic_kind,
        "rationale": rationale,
        "material_hooks": hooks,
        "relation": relation,
        "sources": sources or ["workflow_source"],
        "input_type": input_type,
    }


